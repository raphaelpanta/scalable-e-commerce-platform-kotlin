// Performance suite of feature 004 (T115): SC-002 and SC-003 against the Compose stack through the gateway.
//
//   browse    anonymous shoppers: list a category, search a term, open a product (SC-002 p95 < 1 s at 10,000 products;
//             SC-003 1,000 concurrent browsers without errors)
//   checkout  signed-in shoppers: add a product to the account cart, read the cart revision, place the order
//             (SC-003 100 concurrent checkouts; the only tolerated refusal is a stock refusal)
//
// Run it with run.sh (container, 10k dataset, summary file); README.md explains the prerequisites. Environment:
//   GATEWAY_URL      http://localhost:8080   MAILPIT_URL    http://localhost:8025
//   BROWSE_VUS       1000                    CHECKOUT_VUS   100         (0 disables the scenario)
//   RAMP_UP          2m                      DURATION       3m          (hold time at full load)
//   THINK_TIME       1     seconds between two requests of a browsing shopper (randomised 0.5x..1.5x)
//   CHECKOUT_PACE    5     minimum seconds between two orders of one shopper (checkout tier: 20 per minute/account)
//   PERF_PRODUCTS    10000 size of the dataset of seed-10k.sql; MIN_PRODUCTS (default the same) is the pre-flight floor
//   MAIL_WAIT_S      60    how long a shopper waits for its verification email
//   MAX_429_RETRIES  8     gateway 429 answers retried (after Retry-After) before a call counts as failed
//   SUMMARY_PATH     results/summary.json
