const MAILPIT_URL = (__ENV.MAILPIT_URL || 'http://localhost:8025').replace(/\/+$/, '');
const BROWSE_VUS = intEnv('BROWSE_VUS', 1000);
const CHECKOUT_VUS = intEnv('CHECKOUT_VUS', 100);
const RAMP_UP = __ENV.RAMP_UP || '2m';
const DURATION = __ENV.DURATION || '3m';
const THINK_TIME = numEnv('THINK_TIME', 1);
const CHECKOUT_PACE = numEnv('CHECKOUT_PACE', 5);
const PERF_PRODUCTS = intEnv('PERF_PRODUCTS', 10000);
const MIN_PRODUCTS = intEnv('MIN_PRODUCTS', PERF_PRODUCTS);
const MAIL_WAIT_S = numEnv('MAIL_WAIT_S', 60);
const MAX_429_RETRIES = intEnv('MAX_429_RETRIES', 8);
const SUMMARY_PATH = __ENV.SUMMARY_PATH || 'results/summary.json';

