function rampingScenario(exec_, vus) {
  return {
    executor: 'ramping-vus',
    exec: exec_,
    startVUs: 0,
    stages: [
      { duration: RAMP_UP, target: vus },
      { duration: DURATION, target: vus },
    ],
    gracefulRampDown: '10s',
    gracefulStop: '30s',
  };
}

