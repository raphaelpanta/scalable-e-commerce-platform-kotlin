export function setup() {
  const probe = http.get(`${GATEWAY_URL}/api/v1/catalog/products?size=1`);
  if (probe.status !== 200) {
    exec.test.abort(`pre-flight: GET /api/v1/catalog/products answered ${probe.status}; is the stack up at ${GATEWAY_URL}?`);
  }
  const total = probe.json('totalItems');
  if (total < MIN_PRODUCTS) {
    exec.test.abort(`pre-flight: the catalogue has ${total} products, ${MIN_PRODUCTS} expected; apply platform/perf/seed-10k-apply.sh`);
  }
  const first = http.get(`${GATEWAY_URL}/api/v1/catalog/products/${productId(1)}`);
  if (first.status !== 200) {
    exec.test.abort(`pre-flight: product ${productId(1)} answered ${first.status}; the dataset of seed-10k.sql is not loaded`);
  }
  if (CHECKOUT_VUS > 0) {
    const mail = http.get(`${MAILPIT_URL}/api/v1/info`);
    if (mail.status !== 200) {
      exec.test.abort(`pre-flight: Mailpit answered ${mail.status} at ${MAILPIT_URL}; checkout shoppers need it for the verification email`);
    }
  }

  let categories = SEED_CATEGORIES;
  const listed = http.get(`${GATEWAY_URL}/api/v1/catalog/categories?size=100`);
  if (listed.status === 200) {
    const ids = (listed.json('items') || []).map((c) => c.id);
    const known = SEED_CATEGORIES.filter((id) => ids.indexOf(id) >= 0);
    categories = known.length > 0 ? known : ids.length > 0 ? ids : SEED_CATEGORIES;
  }
  return { runId: Date.now().toString(36), categories };
}

