export function browse(data) {
  const list = browseGet(
    `/api/v1/catalog/products?categoryId=${pick(data.categories)}&page=${randomInt(0, 9)}&size=20`,
    'browse_list',
    'GET /api/v1/catalog/products?categoryId',
  );
  check(list, { 'list: 200 with items': (r) => r.status === 200 && r.body.indexOf('"items"') >= 0 });
  sleep(think());

  const search = browseGet(
    `/api/v1/catalog/products?q=${encodeURIComponent(searchTerm())}&size=20`,
    'browse_search',
    'GET /api/v1/catalog/products?q',
  );
  check(search, { 'search: 200 with items': (r) => r.status === 200 && r.body.indexOf('"items"') >= 0 });
  sleep(think());

  const detail = browseGet(
    `/api/v1/catalog/products/${productId(randomInt(1, PERF_PRODUCTS))}`,
    'browse_detail',
    'GET /api/v1/catalog/products/{id}',
  );
  check(detail, { 'detail: 200 with price': (r) => r.status === 200 && r.body.indexOf('"price"') >= 0 });
  sleep(think());
}

function browseGet(path, kind, name) {
  const res = http.get(`${GATEWAY_URL}${path}`, { tags: { kind, name }, responseCallback: EXPECT_BROWSE });
  if (res.status === 429) {
    // No back-off here: a 429 while browsing means the gateway's browse tier was not lifted (README).
    throttled.add(1, { kind });
  }
  return res;
}

function searchTerm() {
  switch (randomInt(0, 3)) {
    case 0:
      return pick(NOUNS);
    case 1:
      return pick(ADJECTIVES);
    case 2:
      return `${pick(ADJECTIVES)} ${pick(NOUNS)}`;
    default:
      return `${pick(NOUNS)} ${randomInt(1, PERF_PRODUCTS)}`;
  }
}

