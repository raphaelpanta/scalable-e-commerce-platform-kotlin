function intEnv(name, fallback) {
  const value = parseInt(__ENV[name], 10);
  return isNaN(value) ? fallback : value;
}

function numEnv(name, fallback) {
  const value = parseFloat(__ENV[name]);
  return isNaN(value) ? fallback : value;
}

// Deterministic id of PERF product n: keep in sync with seed-10k.sql.
function productId(n) {
  return `9e4f0000-0000-4000-8000-${String(n).padStart(12, '0')}`;
}

function randomInt(min, max) {
  return min + Math.floor(Math.random() * (max - min + 1));
}

function pick(items) {
  return items[Math.floor(Math.random() * items.length)];
}

function think() {
  return THINK_TIME * (0.5 + Math.random());
}

function randomHex(length) {
  let out = '';
  while (out.length < length) out += Math.floor(Math.random() * 16).toString(16);
  return out;
}

function uuid() {
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = Math.floor(Math.random() * 16);
    return (c === 'x' ? r : (r & 0x3) | 0x8).toString(16);
  });
}

function safeJson(res, selector) {
  try {
    return res.json(selector);
  } catch (e) {
    return null;
  }
}

