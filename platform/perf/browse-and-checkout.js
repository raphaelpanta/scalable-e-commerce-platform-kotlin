// Per-VU state: k6 keeps module-level variables between the iterations of one VU, so a shopper is onboarded once
// (stage 0..4) and then loops over orders. A failed stage is retried at the next iteration, not started over.
const shopper = {
  stage: 0, // 0 new, 1 registered, 2 verified, 3 signed in, 4 has an address
  email: null,
  password: null,
  accessToken: null,
  refreshToken: null,
  expiresAtMs: 0,
  addressId: null,
  loggedFailures: 0,
};

export function checkout(data) {
  const started = Date.now();
  if (shopper.stage < 4) {
    onboard(data.runId);
    if (shopper.stage < 4) {
      sleep(5); // wait before the next attempt at the failed stage
      return;
    }
  }
  placeOrder();
  sleep(Math.max(0.5, CHECKOUT_PACE - (Date.now() - started) / 1000));
}

function onboard(runId) {
  if (shopper.email === null) {
    shopper.email = `perf+${runId}-${exec.vu.idInTest}@ecommerce.example`;
    shopper.password = `Shopper-${randomHex(8)}-Pw!`;
  }
  if (shopper.stage === 0) {
    const res = gateway('POST', '/api/v1/identity/accounts', {
      email: shopper.email,
      password: shopper.password,
      displayName: 'Perf Shopper',
    }, {}, 'register');
    if (!outcome('register', res.status === 202 || res.status === 201, res)) return;
    shopper.stage = 1;
  }
  if (shopper.stage === 1) {
    const token = awaitVerificationToken(shopper.email);
    if (!outcome('verification-mail', token !== null, null)) return;
    const res = gateway('POST', '/api/v1/identity/accounts/verify-email', { token }, {}, 'verify');
    if (!outcome('verify', res.status === 204, res)) return;
    shopper.stage = 2;
  }
  if (shopper.stage === 2) {
    if (!signIn()) return;
    shopper.stage = 3;
  }
  if (shopper.stage === 3) {
    const res = gateway('POST', '/api/v1/identity/accounts/me/addresses', CHECKOUT_ADDRESS, bearer(), 'address');
    if (!outcome('address', res.status === 201, res)) return;
    shopper.addressId = safeJson(res, 'id');
    shopper.stage = 4;
  }
}

function signIn() {
  const res = gateway('POST', '/api/v1/identity/sessions', { email: shopper.email, password: shopper.password }, {}, 'sign_in');
  if (!outcome('sign-in', res.status === 200, res)) return false;
  keepSession(res);
  return true;
}

// Access tokens live 15 minutes (expiresIn 900): renew one minute early, by refresh token, falling back to sign-in.
function ensureSession() {
  if (Date.now() < shopper.expiresAtMs - 60000) return true;
  if (shopper.refreshToken !== null) {
    const res = gateway('POST', '/api/v1/identity/sessions/refresh', { refreshToken: shopper.refreshToken }, {}, 'refresh');
    if (res.status === 200) {
      keepSession(res);
      return true;
    }
  }
  return signIn();
}

function keepSession(res) {
  shopper.accessToken = safeJson(res, 'accessToken');
  shopper.refreshToken = safeJson(res, 'refreshToken');
  shopper.expiresAtMs = Date.now() + (safeJson(res, 'expiresIn') || 900) * 1000;
}

function bearer() {
  return { Authorization: `Bearer ${shopper.accessToken}` };
}

function placeOrder() {
  if (!ensureSession()) return;
  const auth = bearer();

  // 1. add a random product of the dataset to the account cart
  const productIdValue = productId(randomInt(1, PERF_PRODUCTS));
  const add = gateway('POST', '/api/v1/cart/lines', { productId: productIdValue, quantity: 1 }, auth, 'cart_add', EXPECT_CART_ADD);
  cartAddMs.add(add.timings.duration);
  if (add.status === 422 && isStockRefusal(add)) {
    stockRefusals.add(1, { step: 'cart_add' });
    checkoutErrors.add(false);
    return;
  }
  if (!outcome('cart-add', add.status === 201, add)) {
    clearCart(auth);
    return;
  }

  // 2. read the cart for its opaque revision
  const cart = gateway('GET', '/api/v1/cart', null, auth, 'cart_read');
  const revision = cart.status === 200 ? safeJson(cart, 'revision') : null;
  if (!outcome('cart-read', revision !== null && revision !== undefined, cart)) {
    clearCart(auth);
    return;
  }

  // 3. place the order; the key is fresh per order and kept across 429 retries of this call
  const order = gateway(
    'POST',
    '/api/v1/orders',
    { addressId: shopper.addressId, cartRevision: revision, paymentMethod: { type: 'card', token: 'tok_sim_approve_4242' } },
    Object.assign({ 'Idempotency-Key': uuid(), 'X-Correlation-Id': uuid() }, auth),
    'order_place',
    EXPECT_ORDER,
  );
  orderMs.add(order.timings.duration);
  if (order.status === 201 || order.status === 202) {
    (order.status === 201 ? ordersPlaced : ordersPending).add(1);
    checkoutErrors.add(false);
  } else if (order.status === 409 && isStockRefusal(order)) {
    stockRefusals.add(1, { step: 'order' });
    checkoutErrors.add(false);
    clearCart(auth); // a refused checkout leaves the cart as it was: empty it so the next order starts clean
  } else {
    outcome('order', false, order);
    clearCart(auth);
  }
}

function clearCart(auth) {
  const res = gateway('DELETE', '/api/v1/cart', null, auth, 'cart_clear');
  if (res.status >= 300) outcome('cart-clear', false, res);
}

function isStockRefusal(res) {
  return /problems\/(insufficient-stock|out-of-stock)/.test(res.body || '');
}

// Records the classification of one step in checkout_errors; failures are also counted by step and status and the
// first few per VU are logged (status and problem body only: never credentials or tokens).
function outcome(step, ok, res) {
  checkoutErrors.add(!ok);
  if (ok) return true;
  const status = res === null ? 0 : res.status;
  checkoutFailures.add(1, { step, status: String(status) });
  if (shopper.loggedFailures < 3) {
    shopper.loggedFailures += 1;
    console.warn(`vu ${exec.vu.idInTest}: ${step} failed with status ${status} ${res === null ? '' : String(res.body).substring(0, 300)}`);
  }
  return false;
}

// One gateway call from the checkout scenario. A 429 is retried after the Retry-After the gateway sent (plus jitter),
// up to MAX_429_RETRIES times, with the same body and headers (so an order keeps its Idempotency-Key).
function gateway(method, path, body, headers, kind, expected) {
  const params = {
    headers: Object.assign({ 'Content-Type': 'application/json' }, headers),
    tags: { kind, name: `${method} ${path}` },
    responseCallback: expected || http.expectedStatuses(200, 201, 202, 204),
  };
  const payload = body === null ? null : JSON.stringify(body);
  for (let attempt = 0; ; attempt++) {
    const res = http.request(method, `${GATEWAY_URL}${path}`, payload, params);
    if (res.status !== 429 || attempt >= MAX_429_RETRIES) return res;
    throttled.add(1, { kind });
    sleep(retryAfterSeconds(res) + Math.random());
  }
}

function retryAfterSeconds(res) {
  for (const name in res.headers) {
    if (name.toLowerCase() === 'retry-after') {
      const seconds = parseInt(res.headers[name], 10);
      if (!isNaN(seconds) && seconds > 0) return Math.min(seconds, 120);
    }
  }
  return 5;
}

// Polls Mailpit for the verification email of [email]; returns its token or null after MAIL_WAIT_S seconds.
function awaitVerificationToken(email) {
  const query = encodeURIComponent(`to:"${email}"`);
  const deadline = Date.now() + MAIL_WAIT_S * 1000;
  const tags = { kind: 'mailpit', name: 'GET mailpit' };
  while (Date.now() < deadline) {
    const found = http.get(`${MAILPIT_URL}/api/v1/search?query=${query}&limit=5`, { tags, responseCallback: http.expectedStatuses(200) });
    if (found.status === 200) {
      const messages = safeJson(found, 'messages') || [];
      for (const message of messages) {
        const full = http.get(`${MAILPIT_URL}/api/v1/message/${message.ID}`, { tags, responseCallback: http.expectedStatuses(200) });
        const token = full.status === 200 ? tokenIn(full) : null;
        if (token !== null) return token;
      }
    }
    sleep(2);
  }
  return null;
}

// Same extraction as the acceptance suite's MailpitClient: ?token= in a link, else "token: <value>" in the text.
function tokenIn(res) {
  let message;
  try {
    message = res.json();
  } catch (e) {
    return null;
  }
  const text = message.Text && message.Text.trim() !== '' ? message.Text : String(message.HTML || '').replace(/<[^>]+>/g, ' ');
  const linked = /[?&;]token=([A-Za-z0-9._~%-]+)/.exec(text);
  if (linked) return decodeURIComponent(linked[1]);
  const plain = /\btoken\b\W{1,3}([A-Za-z0-9._~-]{8,})/i.exec(text);
  return plain ? plain[1] : null;
}

